export type OutlinerStrings = { [K in keyof (typeof STRINGS)["en"]]: string };

/** Strings for a locale ("ko", "ko-KR", …). `overrides` replaces single entries. */
export function outlinerStrings(locale?: string, overrides?: Partial<OutlinerStrings>): OutlinerStrings {
    const lang = (locale ?? "en").slice(0, 2).toLowerCase() as keyof typeof STRINGS;
    return { ...(STRINGS[lang] ?? STRINGS.en), ...overrides };
}
